# Builds the fixture: a repo whose format_command (in .agentic-workflow-kit.json) is a small
# formatter that strips trailing spaces and logs each path it is given, a generated Go client, a
# skill with no description, a CLAUDE.md naming one real and one missing skill, and a file whose
# name holds shell syntax.
set -euo pipefail
DIR="$1"
export GIT_AUTHOR_NAME=example GIT_AUTHOR_EMAIL=example@example.com GIT_COMMITTER_NAME=example GIT_COMMITTER_EMAIL=example@example.com
git init -q -b main "$DIR/repo"; cd "$DIR/repo"
mkdir -p tools api src .claude/skills/release-notes
cat > tools/fmt.sh <<'SH'
#!/bin/sh
printf '%s\n' "$1" >> fmt.log
awk '{ sub(/[ \t]+$/, "") } 1' "$1" > "$1.fmt" && mv "$1.fmt" "$1"
SH
printf '{"format_command": "sh tools/fmt.sh {file}"}\n' > .agentic-workflow-kit.json
printf '// Code generated by openapi-gen. DO NOT EDIT.\npackage api\n' > api/client.gen.go
printf 'package src\n\nfunc lastPage(n, size int) int {   \n\treturn (n + size - 1) / size\n}\n' > src/pager.go
printf -- '---\nname: release-notes\n---\n\nDraft the release notes.\n' > .claude/skills/release-notes/SKILL.md
printf '# app\n\nRun `/release-notes` before a tag, `/review-panel` before a PR, `/deploy-staging` after.\n' > CLAUDE.md
printf 'todo   \n' > 'notes;touch pwned.txt'
git add -A; git commit -qm base
mkdir -p "$DIR/elsewhere" "$DIR/tmp"
printf 'scratch   \n' > "$DIR/elsewhere/scratch.go"
