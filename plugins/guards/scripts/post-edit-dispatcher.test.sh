# Tests for post-edit-dispatcher.sh and its lib/check-*.sh routes. No dependencies
# beyond git and jq. Run: bash post-edit-dispatcher.test.sh
#
# Two layers:
#   1. Behaviour: dispatcher mechanics (root resolution from the edited file's own
#      worktree, a new file in a new folder, the traversal guard, MultiEdit, a large
#      message) and fire/silent cases per route, as tables.
#   2. Drift guard: the lib files on disk, the routes the dispatcher sources, the
#      ROUTES registry below and the routes a case fires must all agree, so a new
#      check cannot ship untested.
set -uo pipefail

HOOKDIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DISP="$HOOKDIR/post-edit-dispatcher.sh"
LIBDIR="$HOOKDIR/lib"
command -v jq  >/dev/null 2>&1 || { echo "SKIP: jq not installed";  exit 0; }
command -v git >/dev/null 2>&1 || { echo "SKIP: git not installed"; exit 0; }

PASS=0; FAIL=0
ok()    { PASS=$((PASS+1)); printf '  ok   %s\n' "$1"; }
bad()   { FAIL=$((FAIL+1)); printf '  FAIL %s\n' "$1"; }
eq()    { [ "$2" = "$3" ] && ok "$1" || bad "$1 (got [$2] want [$3])"; }

# A throwaway git repo whose root is NOT this repo: proves the dispatcher resolves
# the root from the edited file's worktree, not from CLAUDE_PROJECT_DIR.
REPO=$(cd "$(mktemp -d)" && pwd -P)
trap 'rm -rf "$REPO"' EXIT
( cd "$REPO" && git init -q )

mkf()     { local p="$REPO/$1"; mkdir -p "$(dirname "$p")"; printf '%s' "$2" > "$p"; }
payload() { jq -nc --arg fp "$1" '{tool_input:{file_path:$fp,new_string:"x"}}'; }
fire()    { payload "$REPO/$1" | bash "$DISP"; }
ctx()     { jq -r '.hookSpecificOutput.additionalContext // ""' 2>/dev/null; }

COVERED=""
mark() { COVERED="$COVERED $1"; }

echo "post-edit-dispatcher.sh tests:"

# ── Route cases ──────────────────────────────────────────────────────────────
# Rows: name | file | content (printf format) | expected substring of the
# additionalContext, or "-" for no output at all | route the case covers (or "-").
mkdir -p "$REPO/.claude/skills/local-skill"   # a repo skill, for the DOC-002 rows
CASES=(
  "go generated header fires|gen/api.pb.go|// Code generated by protoc-gen-go. DO NOT EDIT.\npackage gen\n|GENERATED FILE|check-generated.sh"
  "@generated marker fires|web/schema.ts|/* @generated by a codegen tool */\nexport type X = 1\n|GENERATED FILE|-"
  "do-not-edit then generated fires|cfg/out.yaml|# DO NOT EDIT: this file is generated by make config\nkey: 1\n|GENERATED FILE|-"
  "marker past line 10 is ignored|src/late.go|package p\n\n\n\n\n\n\n\n\n\n\n// Code generated by x. DO NOT EDIT.\n|-|-"
  "hand-written file silent|src/hand.go|package p\n// generated values live elsewhere\n|-|-"
  "CLAUDE.md over 200 lines DOC-001|big/CLAUDE.md|%s|DOC-001|check-docs-md.sh"
  "small CLAUDE.md with a built-in ref silent|ok/CLAUDE.md|# Small\nUse \`/compact\` when needed.\n|-|-"
  "small CLAUDE.md with a kit skill ref silent|kit/CLAUDE.md|# Small\nRun \`/review-panel\` before a PR.\n|-|-"
  "CLAUDE.md with a broken skill ref DOC-002|ref/CLAUDE.md|# Small\nRun \`/no-such-skill\` first.\n|DOC-002|-"
  "CLAUDE.md with a repo skill ref silent|loc/CLAUDE.md|# Small\nRun \`/local-skill\` first.\n|-|-"
  "SKILL.md over 500 lines DOC-003|bigskill/SKILL.md|---\nname: x\ndescription: y\n---\n%s|DOC-003|-"
  "SKILL.md without frontmatter DOC-004|nofm/SKILL.md|# no frontmatter\nbody\n|DOC-004|-"
  "SKILL.md without description DOC-004|nodesc/SKILL.md|---\nname: x\n---\nbody\n|DOC-004|-"
  "README.md is not routed to docs checks|docs/README.md|%s|-|-"
)
for row in "${CASES[@]}"; do
  IFS='|' read -r name file fmt want route <<<"$row"
  case "$name" in
    *"CLAUDE.md over 200"*|*"README.md is not"*) content=$(seq 1 250) ;;
    *"SKILL.md over 500"*) content=$(printf -- "$fmt" "$(seq 1 501)") ;;
    *) content=$(printf -- "$fmt") ;;
  esac
  mkf "$file" "$content"
  out=$(fire "$file"); rc=$?
  if [ "$want" = "-" ]; then
    eq "$name" "${#out}:$rc" "0:0"
  else
    c=$(printf '%s' "$out" | ctx)
    case "$c" in *"$want"*) ok "$name" ;; *) bad "$name (missing [$want] in [$c])" ;; esac
  fi
  [ "$route" != "-" ] && mark "$route"
done

# ── Mechanics ─────────────────────────────────────────────────────────────────
# A bogus CLAUDE_PROJECT_DIR does not stop routing: the root comes from the file.
mkf root/CLAUDE.md "$(seq 1 250)"
wt=$(payload "$REPO/root/CLAUDE.md" | CLAUDE_PROJECT_DIR=/bogus/nope bash "$DISP" | ctx)
case "$wt" in *DOC-001*) ok "root from the file's worktree, not CLAUDE_PROJECT_DIR" ;; *) bad "worktree root resolution ($wt)" ;; esac

# MultiEdit payloads carry file_path at the top level too.
mkf me/CLAUDE.md "$(seq 1 250)"
me=$(jq -nc --arg fp "$REPO/me/CLAUDE.md" '{tool_input:{file_path:$fp,edits:[{old_string:"a",new_string:"b"}]}}' | bash "$DISP" | ctx)
case "$me" in *DOC-001*) ok "MultiEdit payload routed" ;; *) bad "MultiEdit payload ($me)" ;; esac

# Many warnings in one message stay a valid envelope and exit 0.
mkf many/CLAUDE.md "$(seq 1 250)"
manyout=$(fire many/CLAUDE.md); manyrc=$?
eq "large message exit 0" "$manyrc" "0"
eq "large message valid envelope" "$(printf '%s' "$manyout" | jq -r '.hookSpecificOutput.hookEventName' 2>/dev/null)" "PostToolUse"

# A path with a .. segment outside git is ignored (traversal guard).
NONGIT=$(mktemp -d)
dd=$(jq -nc --arg fp "$NONGIT/sub/../CLAUDE.md" '{tool_input:{file_path:$fp}}' | CLAUDE_PROJECT_DIR="$NONGIT" bash "$DISP")
eq "dotdot path outside git silent" "${#dd}" "0"
rm -rf "$NONGIT"

# No jq on PATH: the advisory hook stays silent with exit 0.
NOJQ=$(mktemp -d)
for t in bash sh git cat sed tr grep dirname basename head awk wc env; do
  p=$(command -v "$t" 2>/dev/null) && [ -n "$p" ] && ln -sf "$p" "$NOJQ/$t"
done
nj=$(printf '{"tool_input":{"file_path":"%s"}}' "$REPO/big/CLAUDE.md" | PATH="$NOJQ" "$(command -v bash)" "$DISP" 2>&1); rc=$?
eq "no jq: silent exit 0" "${#nj}:$rc" "0:0"
rm -rf "$NOJQ"

# Empty and malformed input exit 0 silently.
for input in '' 'not json {{' '{"tool_input":{}}'; do
  o=$(printf '%s' "$input" | bash "$DISP" 2>/dev/null); rc=$?
  eq "input [$input] silent exit 0" "${#o}:$rc" "0:0"
done

# ── Drift guard ───────────────────────────────────────────────────────────────
ROUTES=(check-generated.sh check-docs-md.sh)
libs=$(cd "$LIBDIR" && ls check-*.sh 2>/dev/null | sort -u)
wired=$(grep -oE '\. "\$LIB/check-[a-z-]+\.sh"' "$DISP" | grep -oE 'check-[a-z-]+\.sh' | sort -u)
registry=$(printf '%s\n' "${ROUTES[@]}" | sort -u)
covered=$(printf '%s\n' $COVERED | sort -u | grep .)
eq "drift: lib files == dispatcher source arms" "$libs" "$wired"
eq "drift: lib files == test ROUTES registry"   "$libs" "$registry"
eq "drift: every ROUTE has a firing case"        "$registry" "$covered"

echo "----"
echo "PASS=$PASS FAIL=$FAIL"
[ "$FAIL" -eq 0 ]
